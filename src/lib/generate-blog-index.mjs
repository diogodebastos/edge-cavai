#!/usr/bin/env node
import fs from "fs";
import path from "path";
import { marked } from "marked";

const blogDir = path.join(process.cwd(), "src", "content", "blog");
const outFile = path.join(blogDir, "index.ts");

if (!fs.existsSync(blogDir)) {
  console.error("Blog directory not found:", blogDir);
  process.exit(1);
}

const files = fs
  .readdirSync(blogDir)
  .filter((f) => f.endsWith(".md"))
  .sort((a, b) => {
    const na = Number((a.match(/\d+/g) || []).slice(-1)[0] || 0);
    const nb = Number((b.match(/\d+/g) || []).slice(-1)[0] || 0);
    return nb - na;
  });

function extractTitle(md) {
  for (const line of md.split("\n")) {
    const t = line.trim();
    if (t.startsWith("# ")) return t.slice(2);
  }
  return "Untitled";
}

function extractExcerpt(md) {
  const lines = md.split("\n");
  let sawTitle = false;
  for (const line of lines) {
    const t = line.trim();
    if (!t) continue;
    if (t.startsWith("# ")) { sawTitle = true; continue; }
    if (!sawTitle) continue;
    if (t.startsWith("#") || t.startsWith("---") || t.startsWith("![")) continue;
    // strip markdown emphasis/links lightly
    const plain = t
      .replace(/^\*+|\*+$/g, "")
      .replace(/!\[[^\]]*]\([^)]*\)/g, "")
      .replace(/\[([^\]]+)]\([^)]+\)/g, "$1")
      .replace(/[*_`]/g, "");
    if (plain.length < 20) continue;
    return plain.length > 180 ? plain.slice(0, 177).trimEnd() + "…" : plain;
  }
  return "";
}

function readTime(md) {
  const words = md.replace(/[#*_`>\-]/g, " ").split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.round(words / 220));
}

const entries = files.map((file) => {
  const base = path.basename(file, ".md");
  const slug = base.replace(/_/g, "-");
  const md = fs.readFileSync(path.join(blogDir, file), "utf8");
  const title = extractTitle(md);
  const excerpt = extractExcerpt(md);
  const minutes = readTime(md);
  const html = marked.parse(md, { async: false });
  return { slug, title, excerpt, minutes, html };
});

const json = JSON.stringify(
  entries.reduce((acc, e) => {
    acc[e.slug] = { title: e.title, excerpt: e.excerpt, minutes: e.minutes, html: e.html };
    return acc;
  }, {}),
  null,
  2,
);

const content = `/* Generated by src/lib/generate-blog-index.mjs — do not edit. */
export type BlogEntry = { title: string; excerpt: string; minutes: number; html: string };
const posts: Record<string, BlogEntry> = ${json};
export default posts;
`;

const prev = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : null;
if (prev === content) {
  console.log("No changes to", outFile);
} else {
  fs.writeFileSync(outFile, content);
  console.log("Wrote", outFile);
}

/* ── CV pre-render ── */
const cvMdPath = path.join(process.cwd(), "src", "content", "cv.md");
const cvOutPath = path.join(process.cwd(), "src", "content", "cv-html.ts");
if (fs.existsSync(cvMdPath)) {
  const cvMd = fs.readFileSync(cvMdPath, "utf8");
  const cvHtml = marked.parse(cvMd, { async: false });
  const cvOut = `/* Generated by src/lib/generate-blog-index.mjs — do not edit. */
const cvHtml: string = ${JSON.stringify(cvHtml)};
export default cvHtml;
`;
  const cvPrev = fs.existsSync(cvOutPath) ? fs.readFileSync(cvOutPath, "utf8") : null;
  if (cvPrev === cvOut) {
    console.log("No changes to", cvOutPath);
  } else {
    fs.writeFileSync(cvOutPath, cvOut);
    console.log("Wrote", cvOutPath);
  }
}
